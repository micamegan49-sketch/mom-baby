/* หาแผนป้อนนมที่ตรงกับอายุลูก (เดือน) */
MB.feedPlanFor = function (months) {
  if (months == null) return MB.FEED_PLAN[0];
  return MB.FEED_PLAN.find(p => months >= p.from && months < p.to) || MB.FEED_PLAN[MB.FEED_PLAN.length - 1];
};
/* แนะนำโหมดปั๊มจากอายุลูก */
MB.pumpPlanFor = function (months) {
  if (months == null) return MB.PUMP_PLAN[0];
  if (months < 1.5) return MB.PUMP_PLAN[0];
  if (months < 3) return MB.PUMP_PLAN[1];
  return MB.PUMP_PLAN[2];
};

/* สร้างเวลารอบทั้งวันจาก เวลาเริ่ม (HH:MM) + ระยะห่าง (ชม.) + จำนวนรอบ
   คืน ['06:00','09:00',...] เรียงตามเวลาในหนึ่งวัน (วนข้ามเที่ยงคืนได้) */
MB.milkTimes = function (start, everyHours, count) {
  const [h, m] = String(start || '06:00').split(':').map(Number);
  const step = Math.round((Number(everyHours) || 3) * 60);
  const out = [];
  let t = (h || 0) * 60 + (m || 0);
  for (let i = 0; i < (count || 8); i++) {
    const v = ((t % 1440) + 1440) % 1440;
    out.push(String(Math.floor(v / 60)).padStart(2, '0') + ':' + String(v % 60).padStart(2, '0'));
    t += step;
  }
  return out;
};
